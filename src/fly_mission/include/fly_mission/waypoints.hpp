#pragma once

// ============================================================================
//  waypoints.hpp  ── 航点表（按序走线用）
//
//  一张写死的航点列表，主控 RUN_WAYPOINTS 状态按【列表顺序】逐点飞(target_xy_slam)，
//  到一个点(is_reached 到位判定，含稳定计时)就去下一个，走完整表 → 降落。
//  坐标为 SLAM/camera_init 系(原点=起飞点)，单位米，与主控其余 target_xy_slam 一致。
//
//  ★怎么加/改航点★：直接编辑下面的 WAYPOINTS 列表，一行一个 {x, y}，从上到下就是
//    飞行先后顺序(不需要写序号，下标即顺序)。加多少加多少。改完重编译 fly_mission。
//    例：想按 (3,7)→(4,6) 顺序走，就写 {3.0, 7.0}, {4.0, 6.0},
// ============================================================================

